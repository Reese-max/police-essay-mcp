// Regenerates src/law-references-data.ts with verbatim articles from 全國法規資料庫; `--check` exits 1 when the live text differs.
// Usage: npx tsx scripts/fetch-law-references.ts [--check]
import { promises as fs } from "node:fs";
import path from "node:path";

// Articles police exam answers cite most; triggers that decide when each law is attached live in src/law-references.ts.
const PICK: Record<string, string[]> = {
  C0010001: ["122", "128", "128-1", "128-2", "130", "131", "131-1", "133"], // 刑事訴訟法：搜索、扣押
  A0030297: ["2", "7", "11", "12", "13", "17", "18", "33"], // 資通安全管理法
  A0030305: ["2", "6", "8"], // 資通安全事件通報應變及演練辦法
  I0050021: ["1-1", "2", "5", "6", "12", "15", "16", "18"], // 個人資料保護法
};
const OUT = path.resolve("src/law-references-data.ts");
const unescape = (s: string) => s.replace(/&nbsp;/g, " ").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"')
  .replace(/&#39;/g, "'").replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n))).replace(/&amp;/g, "&");
const strip = (s: string) => unescape(s.replace(/<[^>]+>/g, "")).replace(/\s+/g, "");

async function fetchLaw(pcode: string) {
  const res = await fetch(`https://law.moj.gov.tw/LawClass/LawAll.aspx?pcode=${pcode}`, { headers: { "user-agent": "Mozilla/5.0" } });
  if (!res.ok) throw new Error(`${pcode}: HTTP ${res.status}`);
  const html = await res.text();
  const name = /<title>([\s\S]*?)-全國法規資料庫/.exec(html)?.[1].trim();
  const amended = /id="trLNNDate"[\s\S]*?<td[^>]*>([\s\S]*?)<\/td>/.exec(html)?.[1];
  const cutoff = /法規整編資料截止日：([^<]+)/.exec(html)?.[1];
  if (!name || !amended || !cutoff) throw new Error(`${pcode}: page layout changed (name/amended/cutoff not found)`);
  const articles = new Map<string, string>();
  for (const m of html.matchAll(/<div class="col-no">[\s\S]*?>第 ([0-9-]+) 條<\/a><\/div><div class="col-data"><div class="law-article">([\s\S]*?)<\/div>\s*<\/div><\/div>/g)) {
    const lines = [...m[2].matchAll(/<div class="line-[^"]*">([\s\S]*?)<\/div>/g)].map(x => unescape(x[1].replace(/<[^>]+>/g, "")).trim()).filter(Boolean);
    articles.set(m[1], lines.join("\n"));
  }
  const picked = PICK[pcode].map(no => {
    const text = articles.get(no);
    if (!text) throw new Error(`${name} 第${no}條 not found (deleted or renumbered?)`);
    return { no, text };
  });
  return { pcode, name, amended: strip(amended), cutoff: strip(cutoff), articles: picked };
}

const laws = [];
for (const pcode of Object.keys(PICK)) laws.push(await fetchLaw(pcode));
const cutoff = laws[0].cutoff;
const source = `// Generated by scripts/fetch-law-references.ts from 全國法規資料庫 (law.moj.gov.tw); do not edit by hand.
export const LAW_CUTOFF = ${JSON.stringify(cutoff)};
export const LAW_TEXTS: readonly { pcode: string; name: string; amended: string; articles: readonly { no: string; text: string }[] }[] = ${JSON.stringify(laws.map(({ cutoff: _, ...law }) => law), null, 2)};
`;
if (process.argv.includes("--check")) {
  const current = await fs.readFile(OUT, "utf8").catch(() => "");
  // The cutoff date moves with every database refresh; only article text or amendment dates count as drift.
  const body = (s: string) => s.replace(/export const LAW_CUTOFF = .*\n/, "");
  if (body(current) !== body(source)) { console.error("LAW_REFERENCES_DRIFT：線上條文與 src/law-references-data.ts 不同，請重跑本腳本並檢視 diff。"); process.exit(1); }
  console.log(`LAW_REFERENCES_OK ${laws.length} laws, cutoff ${cutoff}`);
} else {
  await fs.writeFile(OUT, source);
  console.log(`wrote ${OUT}: ${laws.map(l => `${l.name} ${l.articles.length}`).join("、")}，cutoff ${cutoff}`);
}
